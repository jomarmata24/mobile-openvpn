<?php

declare(strict_types=1);

namespace Projectmata\MobileOpenVpn\Build;

use RuntimeException;

final class AndroidEngineInstaller
{
    public function install(string $buildPath, string $packagePath): void
    {
        $root = realpath($buildPath);
        if ($root === false || !is_file($root.'/settings.gradle.kts') || !is_file($root.'/app/build.gradle.kts')) {
            throw new RuntimeException('OpenVPN requires a generated Android Kotlin Gradle project.');
        }

        $gradlePath = $root.'/app/build.gradle.kts';
        $gradle = $this->read($gradlePath);
        if (!preg_match('/compileSdk\s*=\s*(\d+)/', $gradle, $match) || (int) $match[1] < 36) {
            throw new RuntimeException('The bundled OpenVPN runtime requires Android compileSdk 36 or newer.');
        }
        $manifest = $this->read($root.'/app/src/main/AndroidManifest.xml');
        if (preg_match('/<application\b[^>]*android:name\s*=\s*[\'"]([^\'"]+)[\'"]/s', $manifest, $application)
            && $application[1] !== 'de.blinkt.openvpn.core.ICSOpenVPNApplication') {
            throw new RuntimeException('OpenVPN cannot replace a custom Android Application class automatically. Integrate the engine initialization in that Application before using this package.');
        }

        try {
            $metadata = json_decode($this->read($packagePath.'/resources/android/engine/runtime.json'), true, flags: JSON_THROW_ON_ERROR);
        } catch (\JsonException $error) {
            throw new RuntimeException('OpenVPN runtime metadata is invalid. Reinstall the complete package.', previous: $error);
        }
        if (!is_array($metadata)) {
            throw new RuntimeException('OpenVPN runtime metadata must contain an object.');
        }
        $aar = $packagePath.'/resources/android/libs/projectmata-openvpn.aar';
        $sources = $packagePath.'/resources/android/engine/ics-openvpn-sources.zip';
        foreach ([$aar => 'aar_sha256', $sources => 'sources_sha256'] as $file => $key) {
            if (!is_file($file) || !isset($metadata[$key]) || !is_string($metadata[$key]) || !hash_equals($metadata[$key], hash_file('sha256', $file))) {
                throw new RuntimeException('OpenVPN runtime distribution is missing or failed its integrity check. Reinstall the complete package.');
            }
        }

        $libs = $root.'/app/libs';
        if (!is_dir($libs) && !mkdir($libs, 0777, true) && !is_dir($libs)) {
            throw new RuntimeException('Cannot create Android app/libs for the OpenVPN runtime.');
        }
        $destination = $libs.'/projectmata-openvpn.aar';
        if (!is_file($destination) || hash_file('sha256', $destination) !== $metadata['aar_sha256']) {
            if (!copy($aar, $destination)) {
                throw new RuntimeException('Cannot copy the bundled OpenVPN runtime.');
            }
        }

        $this->write($root.'/app/projectmata-openvpn.gradle.kts', <<<'GRADLE'
// Generated by projectmata/mobile-openvpn. Recreated on every native compile.
dependencies {
    add("implementation", files("libs/projectmata-openvpn.aar"))
    add("implementation", "androidx.annotation:annotation:1.9.1")
    add("implementation", "androidx.core:core-ktx:1.13.1")
}

GRADLE
        );

        // Remove only the exact legacy engine dependency, retaining its source checkout.
        $gradle = preg_replace('/^[\t ]*implementation\(project\("\:openvpn\:main"\)\)[\t ]*\R?/m', '', $gradle);
        $gradle = str_replace('implementation(project(":openvpn:main"))', '', $gradle);
        $gradle = preg_replace('~\R?// <projectmata-openvpn>\R.*?// </projectmata-openvpn>\R?~s', '', $gradle);
        $gradle = rtrim($gradle)."\n\n".<<<'GRADLE'
// <projectmata-openvpn>
apply(from = "projectmata-openvpn.gradle.kts")
android {
    packaging.jniLibs {
        useLegacyPackaging = true
        pickFirsts.add("**/libc++_shared.so")
    }
}
// </projectmata-openvpn>
GRADLE
            ."\n";
        $this->write($gradlePath, $gradle);
    }

    private function read(string $path): string
    {
        $content = is_file($path) ? file_get_contents($path) : false;
        if ($content === false) {
            throw new RuntimeException('Required OpenVPN build input is missing: '.basename($path));
        }
        return $content;
    }

    private function write(string $path, string $content): void
    {
        if (file_put_contents($path, $content) === false) {
            throw new RuntimeException('Cannot write OpenVPN build input: '.basename($path));
        }
    }
}
